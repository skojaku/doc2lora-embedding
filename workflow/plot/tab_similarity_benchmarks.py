"""Generate the similarity-benchmark LaTeX tables from the bootstrap summary.

Reads data/uncertainty/uncertainty_summary.csv (benchmark, group, enc,
method, metric, mean, std, ci2_5, ci97_5) and emits two booktabs fragments that
paper/iclr2026/main.tex \\input's:

  figs/similarity_benchmarks.tex      -- tab:similarity (main text): next-paper / topic /
                                         collaboration (one encoder) + S2AND (best encoder
                                         per dataset); raw and adapted only, mean \\std{std},
                                         best per row bold+shaded, second-best underlined.
  figs/similarity_task_transform.tex  -- tab:task-transform (appendix): same rows with the
                                         task-specific transform (+task) column included.
  figs/encoder_matrix.tex             -- tab:encoder-matrix (appendix): raw/+general
                                         per encoder x field x task, means only.

The \\std macro is defined in main.tex. Dual-mode: under Snakemake
(snakemake.input/params/output) or CLI:

  python tab_similarity_benchmarks.py <summary.csv> <similarity.tex> <encoder_matrix.tex>
"""
import csv
import sys
from pathlib import Path

# Encoder whose field tasks are shown in the main-text table.
MAIN_ENC = "qwen"
# Encoder used for every S2AND dataset. We use Qwen3-4B throughout to keep one
# encoder across the whole benchmark; per-encoder field tasks are in tab:encoder-matrix.
S2AND_ENC = {ds: "qwen" for ds in ("zbmath", "qian", "arnetminer", "pubmed", "kisti")}

FIELD_LABELS = [("economics", "Economics"), ("psychology", "Psychology"), ("aps", "Physics")]
TASK_BLOCKS = [
    ("next_paper", "Next-paper (AUC)"),
    ("topic", "Topic (macro-F1)"),
    ("collab", "Collaboration (AUC)"),
]
S2AND_LABELS = [
    ("zbmath", "zbMATH"),
    ("qian", "QIAN"),
    ("arnetminer", "ArnetMiner"),
    ("pubmed", "PubMed"),
    ("kisti", "KISTI"),
]
ENCODER_LABELS = [("gemma", "Gemma-2-2b"), ("qwen", "Qwen3-4B"), ("mistral", "Mistral-7B")]
# Text-encoder baselines shown to the right of the doc2lora columns, in order.
# "specter2" becomes "specter" for the name_disambig benchmark (handled in methods()).
# EmbeddingGemma has field-task rows only; its disambiguation cells render as "--".
# Column order, strongest first, matching the row order of fig:similarity
# (workflow/plot/fig_similarity_benchmarks.py ROWS) so the two read together.
TEXT_ENCODERS = [
    ("sbert", "SBERT"),
    ("gte", "GTE"),
    ("embeddinggemma", "Emb.Gemma"),
    ("instructor", "Instructor"),
    ("specter2", "SPECTER2"),
]


def load(summary_csv):
    """(benchmark, group, enc, method) -> (mean, std)."""
    with open(summary_csv) as f:
        return {
            (r["benchmark"], r["group"], r["enc"], r["method"]): (float(r["mean"]), float(r["std"]))
            for r in csv.DictReader(f)
        }


def f3(x):
    """0.934 -> '.934' (3 decimals, no leading zero)."""
    return f"{x:.3f}".lstrip("0")


def mark(cells):
    """Format (mean, std)|None cells: bold + dark shading for the row max, underline +
    light shading for the second-highest distinct value (ties share the marking);
    compared at 3 decimals."""
    ranked = sorted({round(c[0], 3) for c in cells if c}, reverse=True)
    best = ranked[0]
    second = ranked[1] if len(ranked) > 1 else None
    out = []
    for c in cells:
        if c is None:
            out.append("--")
            continue
        m, s = round(c[0], 3), f3(round(c[1], 3))
        if m == best:
            out.append(f"\\cellcolor{{gray!25}}\\textbf{{{f3(m)}}}\\std{{{s}}}")
        elif m == second:
            out.append(f"\\cellcolor{{gray!10}}\\underline{{{f3(m)}}}\\std{{{s}}}")
        else:
            out.append(f"{f3(m)}\\std{{{s}}}")
    return out


def present_encoders(D):
    """Text encoders that actually have rows; a column of "--" claims a run."""
    keys = {m for (_, _, _, m) in D}
    return [(k, lab) for k, lab in TEXT_ENCODERS
            if k in keys or ("specter" if k == "specter2" else k) in keys]


def similarity_table(D, main_enc, s2and_enc, with_task):
    """Benchmark table; with_task includes the task-specific transform column."""
    d2l_cols = 3 if with_task else 2
    encoders = present_encoders(D)
    text_cols = len(encoders)
    text_header = "".join(f" & \\texttt{{{label}}}" for _, label in encoders)
    header = "Task & Field / dataset & raw" + (" & +task" if with_task else "") + " & adapted" + text_header + " \\\\"
    lines = [
        "% Auto-generated by workflow/plot/tab_similarity_benchmarks.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        "\\resizebox{\\textwidth}{!}{%",
        f"\\begin{{tabular}}{{@{{}}ll{'c' * (d2l_cols + text_cols)}@{{}}}}",
        "\\toprule",
        f" & & \\multicolumn{{{d2l_cols}}}{{c}}{{\\doctolora}} & \\multicolumn{{{text_cols}}}{{c}}{{text encoders}} \\\\",
        f"\\cmidrule(lr){{3-{2 + d2l_cols}}}\\cmidrule(l){{{3 + d2l_cols}-{2 + d2l_cols + text_cols}}}",
        header,
        "\\midrule",
    ]

    def methods(prefix_raw, prefix_kron, prefix_genkron, bench, group, enc):
        keys = [prefix_raw] + ([prefix_kron] if with_task else []) + [prefix_genkron]
        keys += [
            "specter" if (k == "specter2" and bench == "name_disambig") else k
            for k, _ in encoders
        ]
        return [D.get((bench, group, enc, k)) for k in keys]

    for bench, title in TASK_BLOCKS:
        lines.append(f"\\multirow{{{len(FIELD_LABELS)}}}{{*}}{{{title}}}")
        for group, label in FIELD_LABELS:
            cells = mark(methods(main_enc, f"{main_enc}_kron", f"{main_enc}_genkron", bench, group, main_enc))
            lines.append(f" & {label} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule")
    lines.append(f"\\multirow{{{len(S2AND_LABELS)}}}{{*}}{{Author disamb.\\ (B\\textsuperscript{{3}} F1)}}")
    for ds, label in S2AND_LABELS:
        cells = mark(methods("gene", "gene_kron", "gene_genkron", "name_disambig", ds, s2and_enc[ds]))
        lines.append(f" & {label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "}"]
    return "\n".join(lines) + "\n"


def encoder_matrix_table(D):
    lines = [
        "% Auto-generated by workflow/plot/tab_similarity_benchmarks.py -- do not edit by hand.",
        "\\begin{tabular}{llccc}",
        "\\toprule",
        "Encoder & Field & Next-paper (AUC) & Topic (F1) & Collaboration (AUC) \\\\",
        "\\midrule",
    ]
    for i, (enc, elabel) in enumerate(ENCODER_LABELS):
        lines.append(f"\\multirow{{{len(FIELD_LABELS)}}}{{*}}{{{elabel}}}")
        for group, label in FIELD_LABELS:
            cells = []
            for bench, _ in TASK_BLOCKS:
                variants = [
                    D.get((bench, group, enc, enc)),
                    D.get((bench, group, enc, f"{enc}_genkron")),
                ]
                cells.append("\\,/\\,".join(f3(round(v[0], 3)) if v else "--" for v in variants))
            lines.append(f" & {label} & " + " & ".join(cells) + " \\\\")
        if i < len(ENCODER_LABELS) - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def build(summary_csv, similarity_tex, task_transform_tex, encoder_matrix_tex,
          main_enc=MAIN_ENC, s2and_enc=S2AND_ENC):
    D = load(summary_csv)
    Path(similarity_tex).write_text(similarity_table(D, main_enc, s2and_enc, with_task=False))
    print(f"wrote {similarity_tex}", flush=True)
    Path(task_transform_tex).write_text(similarity_table(D, main_enc, s2and_enc, with_task=True))
    print(f"wrote {task_transform_tex}", flush=True)
    Path(encoder_matrix_tex).write_text(encoder_matrix_table(D))
    print(f"wrote {encoder_matrix_tex}", flush=True)


if __name__ == "__main__":
    if "snakemake" in sys.modules:
        build(
            snakemake.input["summary"],                  # noqa: F821
            snakemake.output["similarity"],              # noqa: F821
            snakemake.output["task_transform"],          # noqa: F821
            snakemake.output["encoder_matrix"],          # noqa: F821
            main_enc=snakemake.params["main_enc"],       # noqa: F821
            s2and_enc=snakemake.params["s2and_enc"],     # noqa: F821
        )
    else:
        build(*sys.argv[1:5])
